class ReadinessError(RuntimeError):
    """A Metal readiness report is malformed or contradicts its claims."""


def _u64(value: Any, field: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise ReadinessError(f"{field} must be an unsigned integer")
    if value < 0 or value > U64_MAX:
        raise ReadinessError(f"{field} is outside u64")
    return value


def _u32(value: Any, field: str) -> int:
    value = _u64(value, field)
    if value > 0xFFFFFFFF:
        raise ReadinessError(f"{field} is outside u32")
    return value


def _sha256_bytes(value: Any, field: str) -> bytes:
    if not isinstance(value, str) or SHA256_RE.fullmatch(value) is None:
        raise ReadinessError(f"{field} must be lowercase SHA-256")
    try:
        result = bytes.fromhex(value)
    except ValueError as exc:
        raise ReadinessError(f"{field} must be lowercase SHA-256") from exc
    if len(result) != 32 or result == bytes(32):
        raise ReadinessError(f"{field} must be nonzero")
    return result


def _hash_u64(hasher: Any, value: int) -> None:
    hasher.update(struct.pack("<Q", value))


def _double_from_bits(value: int) -> float:
    return struct.unpack("<d", struct.pack("<Q", value))[0]


def _float_from_bits(value: int) -> float:
    return struct.unpack("<f", struct.pack("<I", value))[0]


def device_identity_sha256(report: Mapping[str, Any]) -> str:
    hasher = hashlib.sha256()
    hasher.update(DEVICE_IDENTITY_DOMAIN)
    for field in (
        "device_info_abi",
        "device_registry_id",
        "recommended_max_working_set_size",
        "device_location",
        "device_location_number",
        "device_max_threads_x",
        "device_max_threads_y",
        "device_max_threads_z",
        "device_low_power",
        "device_headless",
        "device_removable",
        "device_unified_memory",
    ):
        _hash_u64(hasher, _u64(report.get(field), field))
    return hasher.hexdigest()


