def correctness_sha256(report: Mapping[str, Any]) -> str:
    max_abs_error_bits = _u32(
        report.get("max_abs_error_bits"),
        "max_abs_error_bits",
    )
    maximum = _float_from_bits(max_abs_error_bits)
    passed = (
        math.isfinite(maximum)
        and maximum >= 0
        and maximum <= MAXIMUM_ABS_ERROR
    )
    hasher = hashlib.sha256()
    hasher.update(CORRECTNESS_DOMAIN)
    for value in (
        _u64(
            report.get("workload_evidence_abi"),
            "workload_evidence_abi",
        ),
        max_abs_error_bits,
        int(passed),
        IN_FEATURES,
        OUT_FEATURES,
        GROUP_SIZE,
    ):
        _hash_u64(hasher, value)
    hasher.update(
        _sha256_bytes(
            report.get("oracle_output_sha256"),
            "oracle_output_sha256",
        )
    )
    hasher.update(_sha256_bytes(report.get("output_sha256"), "output_sha256"))
    return hasher.hexdigest()


